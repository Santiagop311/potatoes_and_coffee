const c={ink:'#171511',cream:'#fff8e8',yellow:'#ffca22',red:'#d32f25'};
const num=n=>Number(n.toFixed(4));
function letters(font, text, x, y, size, attrs=''){
 const run=font.layout(text);const s=size/font.unitsPerEm;let advanceX=0,advanceY=0;
 const glyphs=run.glyphs.map((glyph,i)=>{const p=run.positions[i];const out=`<path transform="translate(${num(advanceX+p.xOffset)} ${num(advanceY+p.yOffset)})" d="${glyph.path.toSVG()}"/>`;advanceX+=p.xAdvance;advanceY+=p.yAdvance;return out;}).join('');
 return `<g transform="translate(${x} ${y}) scale(${num(s)} ${num(-s)})" ${attrs}>${glyphs}</g>`;
}
function centered(font,text,cx,y,size,attrs='') {return letters(font,text,num(cx-font.layout(text).advanceWidth*size/font.unitsPerEm/2),y,size,attrs);}
